const pad = (n) => String(n).padStart(2, "0");

/** Дата в формате YYYY-MM-DD через offset дней от сегодня */
function dayAt(offset) {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

/** Ближайший день недели (0 — вс., 6 — сб.) не раньше чем через minOffset дней */
function nextWeekday(weekday, minOffset = 0) {
  for (let off = minOffset; off <= minOffset + 7; off++) {
    const d = new Date(dayAt(off) + "T00:00:00");
    if (d.getDay() === weekday) return off;
  }
  throw new Error("unreachable");
}

