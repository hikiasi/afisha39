function slugify(text, suffix) {
  const map = {
    а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
    и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
    с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch",
    ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
  };
  const base = text
    .toLowerCase()
    .split("")
    .map((ch) => (map[ch] !== undefined ? map[ch] : ch))
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  return `${base}-${suffix}`;
}

function endDate(startDate, durationMin) {
  const d = new Date(startDate);
  d.setMinutes(d.getMinutes() + durationMin);
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}:00`;
}

const events = [];
const seen = new Set();

for (const t of templates) {
  let dates = [];

  if (t.kind === "once") {
    dates = [dayAt(t.dayOffset)];
  } else {
    const first = nextWeekday(W[t.weekday], t.kind === "biweekly" ? 3 : 1);
    const step = t.kind === "biweekly" ? 14 : 7;
    for (let i = 0; i < MAX_REPEATS; i++) {
      const off = first + step * i;
      if (off > HORIZON_DAYS) break;
      dates.push(dayAt(off));
    }
  }

  for (let i = 0; i < dates.length; i++) {
    const startsAt = iso(dates[i], t.time);
    const key = t.title + startsAt;
    if (seen.has(key)) continue;
    seen.add(key);

    const dateTag = dates[i].replaceAll("-", "");
    const id = t.kind === "once"
      ? slugify(t.title, "e" + dateTag)
      : slugify(t.title, "e" + dateTag + "-" + (i + 1));

    events.push({
      id,
      title: t.title,
      categoryId: t.categoryId,
      venueId: t.venueId,
      startsAt,
      endsAt: endDate(startsAt, t.durationMin),
      price: t.price,
      priceNote: t.priceNote || null,
      ageLimit: t.ageLimit || null,
      description: t.description,
      highlights: t.highlights || null,
      recurring: t.kind === "weekly" ? "еженедельно" : t.kind === "biweekly" ? "раз в две недели" : null,
      source: "afisha39-demo-dataset",
    });
  }
}

